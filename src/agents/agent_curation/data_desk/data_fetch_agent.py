"""
data_fetch_agent.py (data desk)
For one paper (method or application - anything that reaches this point):
reads the data-availability text, asks the LLM which datasets are mentioned
and whether each was generated by this paper or reused from elsewhere,
resolves the "reused" case's origin paper via the same reference-list-first
resolver the methods desk uses, matches against the existing DB or creates a
new D_* entry (+ a stub Application paper if the origin paper doesn't exist
yet), and links the paper's own DataID field. Single pass - never recursive,
never queues anything for further processing.

Nothing here writes to the master Excel - everything goes through
common.staging.append_candidate().
"""

import re
from datetime import datetime, timezone

from ...common import config, staging, audit_log
from ...common.doi_utils import normalize_doi
from ...common.llm_client import call_llm_json, LLMError, LLMExhaustedError
from ...common.paper_fetcher import fetch_paper, get_agent_text, is_probably_real_content
from ...common.reference_list_parser import parse_reference_list
from ...common.reference_resolver import resolve_citation, is_confident


def _today_stamp() -> int:
    """Same YYYYMMDD-integer format scan.py already uses for
    Date(added_to_dataset) - reused here since this agent never stamped it
    at all before (found 2026-09-27: neither desk agent stamped a creation
    date on new entries, unlike the scanner and manual entries)."""
    return int(datetime.now(timezone.utc).strftime("%Y%m%d"))

# Per-field review-provenance column added 2026-09-20 - same column name on
# both method_pub and AP_pub (see CLAUDE.md's "Per-field review-provenance
# columns" design decision). Tracks whether THIS paper's dataset list
# specifically has ever been attempted, independent of the whole-row
# REVIEW_STATUS - see compared_methods_agent.py's identical mechanism for the
# two bugs this fixes (zero-found papers never getting stamped -> re-fetched
# forever; auto-N papers being permanently excluded from later passes).
_DATASET_STATUS_COL = "DATASET_REVIEW_STATUS"


def _dataset_status(methods_df, entry_id: str) -> str:
    if _DATASET_STATUS_COL not in methods_df.columns:
        return ""
    row = methods_df.loc[methods_df["entry_id"] == entry_id, _DATASET_STATUS_COL]
    return str(row.iloc[0]).strip().lower() if not row.empty else ""

SYSTEM_PROMPT = """You are a careful research assistant extracting factual information from a \
scientific paper's data availability statement (or, if that wasn't available, the paper's full \
text). Identify every distinct dataset mentioned - whether newly generated by this paper or \
reused from a prior publication or public repository.

If the text describes reusing a dataset from a prior publication AND separately mentions a \
secondary "pre-processed"/"processed"/derived copy of that same data (e.g. "we applied our method \
to the breast cancer IMC dataset [4]... the pre-processed data is available at <link>"), treat this \
as ONE dataset mention describing the ORIGINAL published dataset - set relationship to \
"reused_external" and fill origin_citation_marker/origin_citation_text from the ORIGINAL paper's \
citation, not the secondary processed-data link. Do NOT report the pre-processed copy as a separate \
dataset or prefer its link over the original paper's citation - a real example found 2026-10-04: a \
paper applying InterSTELLAR to "the breast cancer IMC dataset [4]" (with a separate Zenodo link to \
ITS OWN pre-processed copy) should have resolved to citation [4]'s original dataset, not created a \
new entry from the pre-processed-copy link.

Do NOT include a dataset that is purely dissociated single-cell data with no spatial component \
(e.g. plain scRNA-seq or scATAC-seq from dissociated cells, no tissue coordinates/imaging) - this \
project is spatial-omics only. Set "modality" to "non_spatial" for these instead of skipping them \
silently, so it's clear one was seen and deliberately excluded rather than missed. If a paper uses \
BOTH spatial and non-spatial (e.g. dissociated scRNA-seq alongside spatial proteomics) data, only \
report the spatial one(s) - still set modality to "non_spatial" for the dissociated one so it's \
visible in your response, but it will not be added to the database.

For each dataset, ALSO extract whatever of the following the text explicitly states - leave a \
field as an empty string (or 0 for numeric fields) if it isn't stated, never guess:
- organism (e.g. "human", "mouse")
- tissue (the tissue or organ sampled, e.g. "breast", "brain cortex")
- disease (the disease/condition studied, or "healthy" if explicitly described as healthy controls)
- n_images (number of images/sections/ROIs profiled, as a plain integer)
- n_patients (number of patients/donors/subjects, as a plain integer)
- is_in_house (true ONLY if the text explicitly describes this as new, in-house-generated data \
from this paper's own lab - not merely "self_generated" in the sense of being reported for the \
first time in this paper if it was actually produced by a collaborating/external group; false \
otherwise, including for all reused_external data)
- is_simulated (true if this "dataset" is actually SIMULATED/SYNTHETIC data generated to test or \
benchmark a method - e.g. a spatial point-process simulation, synthetic cell coordinates, or a \
simulated expression matrix - rather than real experimental tissue data; false for any genuine \
experimental dataset, even a small pilot one)

Return ONLY a JSON array, nothing else, no markdown fences. Each element:
{
  "relationship": "self_generated" | "reused_external" | "unclear",
  "accession": "repository accession number (e.g. GEO GSExxxxx, ArrayExpress E-MTAB-xxxx), or \
empty string if none given",
  "data_doi": "a DOI printed for the dataset ITSELF (common for Zenodo/Dryad/figshare, rare for \
GEO/ArrayExpress), or empty string",
  "access_link": "a URL where the data can be accessed, or empty string",
  "technique": "the spatial technique used for this dataset if stated (e.g. 'IMC', 'CODEX', \
'MERFISH', 'Visium', 'Xenium', 'seqFISH'), or empty string if not stated",
  "modality": "spatial_proteomics" | "spatial_transcriptomics" | "spatial_multi" | "non_spatial" | \
"unknown",
  "organism": "", "tissue": "", "disease": "", "n_images": 0, "n_patients": 0, "is_in_house": false, \
"is_simulated": false,
  "origin_citation_marker": "ONLY if relationship is reused_external and there is a numbered \
reference (e.g. '15') pointing to the paper that originally generated this data - the number as \
it appears. Empty string otherwise.",
  "origin_citation_text": "ONLY if relationship is reused_external and origin_citation_marker is \
empty - an author-year citation for the original paper (e.g. 'Smith et al., 2020'). Empty \
string otherwise."
}
Do not include preprocessing intermediate files, code repositories, or supplementary figures -
only actual experimental datasets. If nothing is mentioned, return an empty JSON array: []
"""


def _build_user_prompt(paper_entry_id: str, text: str) -> str:
    return f"Data availability text (paper {paper_entry_id}):\n\n{text}"


def _describe_existing_dataset(datasets_df, entry_id: str) -> str:
    """Human-readable label for an EXISTING dataset entry being linked to
    (not created) - added 2026-09-21, same reasoning as
    compared_methods_agent.py's _describe_existing(). Datasets have no
    single "title" column, so this builds a short composite from whatever's
    actually populated (technique/tissue/disease) instead. Review-time text
    only - the actual DataID/Associated data fields written to the master
    stay ID-only."""
    row = datasets_df.loc[datasets_df["entry_id"] == entry_id]
    if row.empty:
        return entry_id
    r = row.iloc[0]
    parts = [str(r.get(f, "") or "").strip() for f in ("spatial_data_method", "tissue", "disease")]
    parts = [p for p in parts if p and p.lower() not in ("nan", "na", "none")]
    desc = ", ".join(parts)
    return f"{entry_id} ({desc})" if desc else entry_id


def _sheet_for_modality(modality: str) -> str:
    """As of the method_pub/AP_pub/data schema there's only one dataset
    sheet - kept as a function (rather than inlining the literal) since
    _id_prefix_for_modality still needs a per-modality answer for ID naming,
    and it's clearer to keep "which sheet" and "which ID prefix" as two
    separate questions even though the sheet answer is now constant."""
    return "data"


def _id_prefix_for_modality(modality: str) -> str:
    m = (modality or "").lower()
    if "multi" in m:
        return "D_MULTI"
    if "proteomic" in m:
        return "D_SP"
    if "transcriptomic" in m:
        return "D_ST"
    return "D_MULTI"  # safest catch-all when genuinely unclear


def _sheet_for_paper_entry(entry_id: str) -> str:
    """Infers which pub sheet a paper entry_id lives in. Application papers
    (including stubs this same agent creates) use the "AP_..." ID prefix;
    everything else is a method_pub entry. Needed because process_paper()
    is shared by both method and application papers (per its own docstring),
    but method_pub/AP_pub are now separate sheets with different columns."""
    return "AP_pub" if str(entry_id).upper().startswith("AP") else "method_pub"


def _data_used_field_for_sheet(sheet: str) -> str:
    """method_pub tracks datasets used via 'DataID (data_used_in_the_paper)';
    AP_pub's equivalent native column is 'Associated data' - reuse that
    instead of creating a stray DataID column on AP_pub rows."""
    return "Associated data" if sheet == "AP_pub" else "DataID (data_used_in_the_paper)"


def _technique_slug(technique: str) -> str:
    """Best-effort ID component from the LLM's free-text technique guess.
    Won't always match your existing hand-picked abbreviation style (e.g.
    'D_ST_COSM16' for CosMx) - flagged as auto-generated via REVIEW_STATUS,
    so treat generated IDs as a starting point to rename on merge, not final."""
    if not technique:
        return "NEW"
    slug = re.sub(r"[^A-Za-z0-9]", "", technique).upper()
    return slug[:10] if slug else "NEW"


def _find_by_accession(datasets_df, accession: str):
    if not accession or "data_accession_number" not in datasets_df.columns:
        return None
    col = datasets_df["data_accession_number"].astype(str).str.strip()
    matches = datasets_df[col == accession.strip()]
    if not matches.empty:
        return matches.iloc[0]["entry_id"]
    return None


_URL_VERSION_SUFFIX_RE = re.compile(r"/v?\d+/?$")


def _normalize_access_link(url: str) -> str:
    """Strips a trailing version-number path segment (e.g. Mendeley's
    '/d87vg86zd8' vs '/d87vg86zd8/3' for a specific version of the same
    dataset) and any trailing slash, so the two are recognized as the same
    underlying dataset. Added 2026-10-04 after a real duplicate: a new
    mention linked to 'https://data.mendeley.com/datasets/d87vg86zd8'
    (no version) didn't match an existing entry already recorded as
    '.../d87vg86zd8/3' - an exact-match comparison alone missed it even
    though both obviously point at the same dataset."""
    return _URL_VERSION_SUFFIX_RE.sub("", str(url or "").strip().rstrip("/"))


def _find_by_access_link(datasets_df, access_link: str):
    """Matches on the access URL (e.g. a Zenodo/Dryad/Mendeley/Dataverse
    link) - added 2026-09-27 after real duplicates were created for datasets
    that DO already exist in the DB but have no DOI/accession recorded on
    the existing entry (older/manually-added rows), so the DOI- and
    accession-based checks above had no shared identifier to match on at
    all (confirmed live: the Schurch/Angelo-Lab TNBC MIBI dataset was
    independently re-created 3-4 separate times this way). Compares the
    version-stripped form of both sides (see _normalize_access_link) - a
    raw URL is already a weaker signal than a DOI/accession, so this still
    isn't fuzzy beyond that one specific, well-understood normalization."""
    if not access_link or "data_acess_link" not in datasets_df.columns:
        return None
    target = _normalize_access_link(access_link)
    if not target:
        return None
    col = datasets_df["data_acess_link"].astype(str).map(_normalize_access_link)
    matches = datasets_df[col == target]
    if not matches.empty:
        return matches.iloc[0]["entry_id"]
    return None


def _append_id_list(existing, new_id: str, sep: str = "; ") -> str:
    existing = "" if existing is None else str(existing).strip()
    if existing in ("", "nan", "NA"):
        return new_id
    ids = [x.strip() for x in re.split(r"[;,]", existing) if x.strip()]
    if new_id not in ids:
        ids.append(new_id)
    return sep.join(ids)


def _lookup_field(df, entry_id: str, column: str):
    row = df.loc[df["entry_id"] == entry_id, column]
    return row.iloc[0] if not row.empty else ""


def _empty_stats(skip_reason: str, llm_exhausted: bool = False) -> dict:
    """Consistent return shape at every early-exit point. skip_reason is
    ALWAYS a non-empty string here (the LLM was never called) - callers
    should show it directly rather than leaving people to infer whether
    0 results means 'skipped' or 'called and found nothing'.
    llm_exhausted is True ONLY when the whole provider/model chain failed
    (LLMExhaustedError) - run_pipeline.py checks this to stop a run early
    instead of repeating the same doomed wait on every remaining paper."""
    return {"linked_ids": [], "total_encountered": 0, "total_resolved": 0,
            "skip_reason": skip_reason, "llm_exhausted": llm_exhausted}


def process_paper(db, paper_entry: dict, fetched: dict = None, reference_map: dict = None) -> dict:
    """
    paper_entry: {"entry_id": ..., "doi": ...} (depth is irrelevant here - not recursive)
    fetched/reference_map: pass these in if the orchestrator already fetched
    this paper for the methods desk pass, to avoid re-fetching/re-parsing.

    Returns {"linked_ids": [...], "total_encountered": N, "total_resolved": M,
    "skip_reason": str or None}. skip_reason is None ONLY when the LLM was
    genuinely called - always check this field rather than inferring from a
    0 count. linked_ids is every D_* entry_id linked or created - nothing
    here feeds back into any queue (this track is never recursive).
    """
    entry_id = paper_entry["entry_id"]
    doi = paper_entry["doi"]
    data_ids_linked = []

    existing_status = _dataset_status(db.methods, entry_id)
    if existing_status in ("auto", "manual"):
        return _empty_stats(f"dataset list already {existing_status} "
                             f"({_DATASET_STATUS_COL}) - not re-attempting")

    if fetched is None:
        fetched = fetch_paper(doi)

    text, _source = get_agent_text(fetched, "data_availability")
    if not text:
        text = fetched.get("text", "")  # many papers don't have a clean heading for this
    if not text:
        staging.append_candidate(
            action="update_field", sheet=_sheet_for_paper_entry(entry_id), entry_id=entry_id, fields={},
            source_paper_entry_id=entry_id, curation_agent="data_fetch_agent",
            curation_model="none", confidence=0.0,
            notes=f"No text available to extract data availability from (fetch source: {fetched['source']}).",
        )
        return _empty_stats(f"no text could be fetched (fetch source: {fetched['source']})")

    if not is_probably_real_content(text):
        staging.append_candidate(
            action="update_field", sheet=_sheet_for_paper_entry(entry_id), entry_id=entry_id, fields={},
            source_paper_entry_id=entry_id, curation_agent="data_fetch_agent",
            curation_model="none", confidence=0.0,
            notes=f"Extracted text (source: {_source}) failed the content quality check - "
                  f"looks like website navigation/boilerplate rather than real article text. "
                  f"Skipped the LLM call to avoid wasting budget on unreliable input.",
        )
        return _empty_stats(f"text (source: {_source}) failed the content-quality check "
                             f"(looked like navigation/boilerplate, not real article text)")

    if config.REQUIRE_ISOLATED_SECTION and _source != "section:data_availability":
        staging.append_candidate(
            action="update_field", sheet=_sheet_for_paper_entry(entry_id), entry_id=entry_id, fields={},
            source_paper_entry_id=entry_id, curation_agent="data_fetch_agent",
            curation_model="none", confidence=0.0,
            notes=f"Could not cleanly isolate the data-availability section (got '{_source}' "
                  f"instead) - skipped the LLM call rather than spend a query on unfocused/"
                  f"low-confidence text.",
        )
        return _empty_stats(f"could not cleanly isolate the data-availability section "
                             f"(got '{_source}' instead of 'section:data_availability') - "
                             f"REQUIRE_ISOLATED_SECTION blocked the LLM call")

    if reference_map is None:
        references_text, _ = get_agent_text(fetched, "references")
        reference_map = parse_reference_list(references_text) if references_text else {}

    try:
        # only_provider="gemini_flash_only" (changed 2026-10-04, narrowed
        # 2026-10-05) - see compared_methods_agent.py's identical change for
        # the full reasoning (Marta explicitly asked for this pass to be
        # pinned to Gemini only, then narrowed further to exclude
        # gemini-3.5-flash-lite too after real staged data showed its
        # empty-result rate is more than double plain flash's).
        extracted, model_used = call_llm_json(
            SYSTEM_PROMPT, _build_user_prompt(entry_id, text),
            only_provider="gemini_flash_only"
        )
    except LLMError as e:
        staging.append_candidate(
            action="update_field", sheet=_sheet_for_paper_entry(entry_id), entry_id=entry_id, fields={},
            source_paper_entry_id=entry_id, curation_agent="data_fetch_agent",
            curation_model="none", confidence=0.0, notes=f"LLM extraction failed: {e}",
        )
        return _empty_stats(f"LLM WAS called but every provider/model failed: {e}",
                             llm_exhausted=isinstance(e, LLMExhaustedError))

    if not isinstance(extracted, list):
        extracted = []

    item_outcomes = []

    for item in extracted:
        item = item or {}
        relationship = (item.get("relationship") or "unclear").strip().lower()
        accession = (item.get("accession") or "").strip()
        data_doi = normalize_doi(item.get("data_doi", ""))
        access_link = (item.get("access_link") or "").strip()
        technique = (item.get("technique") or "").strip()
        modality = (item.get("modality") or "").strip()
        organism = (item.get("organism") or "").strip()
        tissue = (item.get("tissue") or "").strip()
        disease = (item.get("disease") or "").strip()
        n_images = item.get("n_images") or ""
        n_patients = item.get("n_patients") or ""
        is_in_house = bool(item.get("is_in_house"))
        is_simulated = bool(item.get("is_simulated"))
        origin_marker = (item.get("origin_citation_marker") or "").strip()
        origin_text = (item.get("origin_citation_text") or "").strip()

        if modality == "non_spatial":
            # Reject outright, added 2026-09-27 per Marta's explicit ask
            # ("single cell data should not be added") - real example: a
            # paper's own scRNA-seq datasets (alongside its real spatial
            # ones) were previously created as full D_* entries despite
            # being out of this project's spatial-omics-only scope. Not
            # staged at all, not even as needs_review - this is a scope
            # exclusion, not a data-quality issue worth cluttering the
            # review queue with.
            item_outcomes.append({"outcome": "skipped",
                                   "reason": "modality is non_spatial (dissociated/single-cell, "
                                             "out of scope)"})
            continue

        if is_simulated:
            # Simulated/synthetic benchmark data is not a real deposited
            # dataset - link to ONE shared singleton entry per modality
            # (D_SP_simulation / D_ST_simulation, both pre-existing rows -
            # confirmed 2026-10-04) instead of creating a new row per
            # mention. Fixed 2026-10-04 per Marta's explicit ask ("just add
            # them as D_SP_simulation D_ST_simulation"): this previously
            # minted a NEW numbered entry per mention via the
            # technique_part="SIMULATION" id-prefix routing further below -
            # real example, D_MULTI_NEW_20260925277/278 were two separate
            # simulation datasets that should have collapsed into the one
            # shared bucket, not two new rows. Checked BEFORE the
            # accession/DOI/link existence gate below, since simulated data
            # usually has none of those (nothing to deposit) and would
            # otherwise be silently dropped entirely rather than linked.
            sim_id = {"spatial_proteomics": "D_SP_simulation",
                      "spatial_transcriptomics": "D_ST_simulation"}.get(modality)
            if sim_id and sim_id in set(db.datasets["entry_id"]):
                data_ids_linked.append(sim_id)
                item_outcomes.append({"outcome": "linked_existing", "entry_id": sim_id,
                                       "description": _describe_existing_dataset(db.datasets, sim_id),
                                       "matched_by": "simulated_singleton"})
                continue
            # modality is multi/unclear, or no singleton exists for it -
            # fall through to normal handling below (the technique_part=
            # "SIMULATION" id-prefix routing still applies as a fallback,
            # rather than silently dropping a flagged-simulated mention).

        if not accession and not data_doi and not access_link:
            # KNOWN LIMITATION (flagged 2026-09-21, not fixed): a dataset
            # mention with no identifier at all gets dropped here regardless
            # of modality - e.g. a paper self-generating both IMC and IF data
            # with neither formally deposited would lose both. See CLAUDE.md.
            item_outcomes.append({"outcome": "skipped",
                                   "reason": "no accession/data_doi/access_link on this mention"})
            continue  # nothing usable in this mention

        # --- matching against existing DB first - keyed on THIS mention's
        # own accession/DOI, never on the paper's DOI, so a paper with
        # multiple datasets (e.g. IMC + IF) can never get confused between
        # them: each mention only ever matches the specific existing entry
        # that carries its exact identifier. ---
        existing_id = db.doi_index.lookup(data_doi) if data_doi else None
        matched_by = "data_doi" if existing_id else None
        if existing_id is None and accession:
            existing_id = _find_by_accession(db.datasets, accession)
            matched_by = "accession" if existing_id else None
        if existing_id is None and access_link:
            # Added 2026-09-27 - see _find_by_access_link's own docstring
            # for the real duplicates (Schurch/Angelo-Lab MIBI data) this
            # closes a gap on.
            existing_id = _find_by_access_link(db.datasets, access_link)
            matched_by = "access_link" if existing_id else None

        if existing_id:
            data_ids_linked.append(existing_id)
            item_outcomes.append({"outcome": "linked_existing", "entry_id": existing_id,
                                   "description": _describe_existing_dataset(db.datasets, existing_id),
                                   "matched_by": matched_by})
            continue

        # --- not found: resolve who produced this data before creating ---
        paper_doi_field, paper_entry_id_field = "", ""
        origin_confidence = None
        origin_note = ""

        if relationship == "self_generated":
            paper_doi_field, paper_entry_id_field = doi, entry_id
            origin_confidence = 1.0

        elif relationship == "reused_external":
            resolved = resolve_citation(origin_marker, origin_text, reference_map)
            if is_confident(resolved) and resolved["resolved_doi"]:
                origin_confidence = resolved["confidence"]
                origin_doi = resolved["resolved_doi"]
                existing_paper_id = db.doi_index.lookup(origin_doi)
                if existing_paper_id:
                    paper_doi_field, paper_entry_id_field = origin_doi, existing_paper_id
                else:
                    stub_id = db.id_allocator.next_id("AP")
                    staging.append_candidate(
                        action="create_entry", sheet="AP_pub", entry_id=stub_id,
                        fields={
                            "DOI": origin_doi,
                            "category": "Application",
                            "REVIEW_STATUS": config.REVIEW_STATUS_NEEDS_REVIEW,
                            "addition_method": config.ADDITION_METHOD_CITATION_CHASE,
                        },
                        source_paper_entry_id=entry_id, curation_agent="data_fetch_agent",
                        curation_model=model_used, confidence=resolved["confidence"],
                        notes=f"Auto-created stub: original source paper for data reused in {entry_id}.",
                    )
                    db.doi_index.add(origin_doi, stub_id)
                    paper_doi_field, paper_entry_id_field = origin_doi, stub_id
            else:
                origin_note = (" Original paper for this reused dataset could not be confidently "
                               "resolved - paper_DOI left blank for manual linking.")
        else:
            origin_note = " Relationship to source paper unclear - paper_DOI left blank for manual linking."

        sheet = _sheet_for_modality(modality)
        # Simulated/synthetic datasets (e.g. a spatial point-process
        # simulation used only to benchmark a method) get a distinct
        # "SIMULATION" slot instead of a technique slug, added 2026-10-04 per
        # Marta's explicit ask - real example: D_MULTI_NEW_20260925277/278
        # turned out to both be simulation datasets, not real ones,
        # discovered only during manual review, with nothing in the ID or
        # schema distinguishing them from genuine experimental data.
        technique_part = "SIMULATION" if is_simulated else _technique_slug(technique)
        prefix = f"{_id_prefix_for_modality(modality)}_{technique_part}"
        new_id = db.id_allocator.next_id(prefix)

        confident_enough = (relationship == "self_generated") or (
            origin_confidence is not None and origin_confidence >= 0.55
        )
        review_status = config.REVIEW_STATUS_AUTO if confident_enough else config.REVIEW_STATUS_NEEDS_REVIEW

        in_house_note = " Explicitly described as new, in-house-generated data." if is_in_house else ""

        staging.append_candidate(
            action="create_entry", sheet=sheet, entry_id=new_id,
            fields={
                "data_DOI": data_doi,
                "data_accession_number": accession,
                "data_acess_link": access_link,
                "paper_DOI": paper_doi_field,
                "paper_ENTRY_ID": paper_entry_id_field,
                "spatial_data_category": modality,
                "spatial_data_method": technique,
                "REVIEW_STATUS": review_status,
                "addition_method": config.ADDITION_METHOD_CITATION_CHASE,
                # Added 2026-09-27 - previously the schema didn't even ask
                # the LLM for these, so they went unfilled even when stated
                # explicitly in the text (real examples: M_AUTO_63's dataset
                # list, M_AUTO_98's Harvard Dataverse entries).
                "organism": organism,
                "tissue": tissue,
                "disease": disease,
                "N images": n_images,
                "N patients": n_patients,
                "Date(added_to_dataset)": _today_stamp(),
            },
            source_paper_entry_id=entry_id, curation_agent="data_fetch_agent",
            curation_model=model_used, confidence=origin_confidence,
            notes=f"Extracted from data-availability text in {entry_id} "
                  f"(relationship: {relationship}).{origin_note}{in_house_note}",
        )

        if data_doi:
            db.doi_index.add(data_doi, new_id)
        data_ids_linked.append(new_id)
        item_outcomes.append({"outcome": "created_new", "entry_id": new_id,
                               "confidence": origin_confidence, "review_status": review_status})

    audit_log.log_extraction("data_fetch_agent", entry_id, model_used, extracted, item_outcomes)

    paper_sheet = _sheet_for_paper_entry(entry_id)

    # Always stamp the per-field review status once the LLM has genuinely
    # been called, whether or not it found anything - see
    # _DATASET_STATUS_COL's module-level comment for the bug this fixes.
    review_fields = {
        _DATASET_STATUS_COL: "auto",
        "DATASET_REVIEW_AGENT": "data_fetch_agent",
        "DATASET_REVIEW_MODEL": model_used,
        "DATASET_REVIEW_DATE": datetime.now(timezone.utc).isoformat(),
    }

    if data_ids_linked:
        data_used_field = _data_used_field_for_sheet(paper_sheet)
        existing_value = _lookup_field(db.methods, entry_id, data_used_field)
        updated_value = existing_value
        for did in data_ids_linked:
            updated_value = _append_id_list(updated_value, did)

        # Human-readable per-ID breakdown, not just "IDs were appended" -
        # same reasoning as compared_methods_agent.py's identical change.
        added_descriptions = [
            (o.get("description") or o["entry_id"]) for o in item_outcomes
            if o.get("outcome") in ("linked_existing", "created_new") and o.get("entry_id") in data_ids_linked
        ]
        staging.append_candidate(
            action="update_field", sheet=paper_sheet, entry_id=entry_id,
            fields={data_used_field: updated_value, **review_fields},
            source_paper_entry_id=entry_id, curation_agent="data_fetch_agent",
            curation_model=model_used, confidence=None,
            notes="Appended/linked dataset IDs: " + "; ".join(added_descriptions),
        )
    else:
        staging.append_candidate(
            action="update_field", sheet=paper_sheet, entry_id=entry_id,
            fields=review_fields,
            source_paper_entry_id=entry_id, curation_agent="data_fetch_agent",
            curation_model=model_used, confidence=None,
            notes=f"Data desk pass completed - {len(extracted)} dataset mention(s) "
                  f"encountered, none resolved to a linkable/creatable entry."
                  if extracted else
                  "Data desk pass completed - no datasets found in this paper.",
        )

    return {
        "linked_ids": data_ids_linked,
        "total_encountered": len(extracted),
        "total_resolved": len(data_ids_linked),
        "skip_reason": None,
    }
